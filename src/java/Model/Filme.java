public class Filme {
    
    private int id;
    private String nome;
    private String diretor;
    private String ano_publicacao;
    private double preco_aluguel;
    private String status;

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getDiretor() {
        return diretor;
    }

    public void setDiretor(String diretor) {
        this.diretor = diretor;
    }

    public String getAno_publicacao() {
        return ano_publicacao;
    }

    public void setAno_publicacao(String ano_publicacao) {
        this.ano_publicacao = ano_publicacao;
    }

    public double getPreco_aluguel() {
        return preco_aluguel;
    }

    public void setPreco_aluguel(double preco_aluguel) {
        this.preco_aluguel = preco_aluguel;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

   
    
   
}
